#!/usr/bin/env python3
"""
Dump the full project state into a single markdown file for session continuity.

Usage:
    python scripts/project_dump.py

Writes:
    .project_dump.md   (in the repository root)
"""

from __future__ import annotations

import os
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / ".project_dump.md"

SKIP_DIRS = {
    ".git", ".venv", "node_modules", "__pycache__", ".pytest_cache",
    ".ruff_cache", ".mypy_cache", ".next", "dist", "build", "coverage",
    "models", "data", "eval/private", "eval/reports",
}
SKIP_FILES = {
    ".env", ".project_dump.md", "uv.lock", "package-lock.json",
    ".DS_Store",
}
SKIP_EXT = {".pyc", ".pyo", ".so", ".dll", ".dylib", ".onnx", ".db",
            ".sqlite", ".sqlite3", ".pdf", ".png", ".jpg", ".jpeg"}

MAX_FILE_BYTES = 200_000

def is_skipped_dir(name: str) -> bool:
    return name in SKIP_DIRS

def is_skipped_file(path: Path) -> bool:
    if path.name in SKIP_FILES:
        return True
    if path.suffix in SKIP_EXT:
        return True
    return False

def git(*args: str) -> str:
    try:
        out = subprocess.run(
            ["git", *args],
            cwd=ROOT, capture_output=True, text=True, check=False,
        )
        return out.stdout.strip() or out.stderr.strip()
    except FileNotFoundError:
        return "(git is not installed)"

def read_env_keys() -> list[str]:
    env_path = ROOT / ".env"
    if not env_path.exists():
        return []
    keys = []
    for raw in env_path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if "=" in line:
            key = line.split("=", 1)[0].strip()
            if key:
                keys.append(key)
    return keys

def walk() -> list[Path]:
    files: list[Path] = []
    for dirpath, dirnames, filenames in os.walk(ROOT):
        dirnames[:] = [d for d in dirnames if not is_skipped_dir(d)]
        for name in filenames:
            p = Path(dirpath) / name
            try:
                rel = p.relative_to(ROOT)
            except ValueError:
                continue
            if is_skipped_file(p):
                continue
            rel_str = rel.as_posix()
            if rel_str.startswith("eval/private/") or rel_str.startswith("eval/reports/"):
                continue
            files.append(rel)
    return sorted(files, key=lambda p: p.as_posix())

def read_file(path: Path) -> str:
    try:
        data = path.read_bytes()
    except OSError as exc:
        return f"(could not read: {exc})"
    if len(data) > MAX_FILE_BYTES:
        data = data[:MAX_FILE_BYTES] + b"\n... (truncated)\n"
    try:
        return data.decode("utf-8")
    except UnicodeDecodeError:
        return "(binary or non-UTF-8 file, omitted)"

def state_section() -> str:
    state_path = ROOT / "STATE.md"
    if not state_path.exists():
        return "_STATE.md does not exist yet._"
    return state_path.read_text(encoding="utf-8", errors="replace")

def tree_section(files: list[Path]) -> str:
    return "\n".join(f"- `{p.as_posix()}`" for p in files) or "_empty repository_"

def contents_section(files: list[Path]) -> str:
    parts: list[str] = []
    for p in files:
        text = read_file(p)
        # Use HTML <pre> to completely avoid nested backtick issues in markdown
        parts.append(f"### FILE: {p.as_posix()}\n\n<pre>\n{text}\n</pre>\n")
    return "\n".join(parts)

def main() -> int:
    now = datetime.now(timezone.utc).isoformat(timespec="seconds")
    files = walk()

    head = f"""# Project dump — document-qa

Generated at: `{now}`
Repository root: `{ROOT.as_posix()}`

This file is generated by `scripts/project_dump.py`. It is safe to share: it never contains `.env` values, only key names.

## How to use this file

Paste this file into a fresh chat with the assistant. The assistant will read `STATE.md`, the file tree, and any file contents it needs to continue from the last stage. Do not edit this file by hand; re-run the script instead.
"""

    git_status = git("status", "--porcelain=v1")
    git_log = git("log", "--oneline", "-n", "20")
    git_branch = git("rev-parse", "--abbrev-ref", "HEAD")

    env_keys = read_env_keys()
    env_block = "\n".join(f"- `{k}`" for k in env_keys) or "_no .env file_"

    body = f"""
## Current state (STATE.md)

{state_section()}

## Git

Branch: `{git_branch}`

Recent commits:

<pre>
{git_log or "(no commits yet)"}
</pre>

Working tree status:

<pre>
{git_status or "(clean)"}
</pre>

## Environment variable names present in `.env`

{env_block}

## File tree

{tree_section(files)}

## File contents

{contents_section(files)}
"""

    OUT.write_text(head + body, encoding="utf-8")
    print(f"Wrote {OUT} ({OUT.stat().st_size} bytes, {len(files)} files)")
    return 0

if __name__ == "__main__":
    sys.exit(main())